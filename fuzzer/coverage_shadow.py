"""Coverage Shadow: offline post-hoc coverage analysis for agent corpora.

Preserves design decision D2: the agentic loop operates as a pure blackbox without
coverage feedback. Coverage Shadow runs strictly offline / post-hoc on corpora
generated by the agent, mapping inputs to parser states, edge fingerprints, and
strategy attributions.
"""
from __future__ import annotations

import collections
import hashlib
import json
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Iterable

from fuzzer.corpus import iter_corpus
from fuzzer.runner import Outcome, RunResult
from fuzzer.targets import BaseTarget, get_target


@dataclass
class EdgeAttribution:
    """Records which strategy and inputs first discovered a particular edge/state."""
    edge_id: str
    discovered_by_strategy: str
    discovered_at_index: int
    hit_count: int = 1
    sample_sha: str = ""


@dataclass
class CoverageShadowReport:
    """Report generated by post-hoc coverage shadow analysis."""
    total_inputs_analyzed: int
    total_edges_discovered: int
    edges_by_strategy: dict[str, int]
    unique_edges_by_strategy: dict[str, int]
    coverage_timeline: list[dict[str, Any]]
    edge_details: list[EdgeAttribution] = field(default_factory=list)
    analysis_duration_s: float = 0.0

    def to_json(self) -> dict[str, Any]:
        return {
            "total_inputs": self.total_inputs_analyzed,
            "total_edges": self.total_edges_discovered,
            "edges_by_strategy": self.edges_by_strategy,
            "unique_edges_by_strategy": self.unique_edges_by_strategy,
            "timeline_length": len(self.coverage_timeline),
            "analysis_duration_s": round(self.analysis_duration_s, 3),
        }

    def generate_markdown(self) -> str:
        lines = [
            "# Coverage Shadow: Offline Post-Hoc Analysis",
            "",
            f"**Total Inputs:** {self.total_inputs_analyzed:,} | **Total Unique Edges/States Reached:** {self.total_edges_discovered:,}",
            "",
            "## Strategy Coverage Attribution",
            "",
            "| Strategy | Edges Reached | Exclusively Discovered Edges |",
            "|---|---|---|",
        ]
        for strat, edges in sorted(self.edges_by_strategy.items(), key=lambda kv: -kv[1]):
            uniq = self.unique_edges_by_strategy.get(strat, 0)
            lines.append(f"| `{strat}` | {edges:,} | **{uniq:,}** |")

        return "\n".join(lines)


class CoverageShadow:
    """Post-hoc coverage analyzer for agent-generated corpora."""

    def __init__(self, target_name: str = "mxml"):
        self.target: BaseTarget = get_target(target_name)
        self.edge_table: dict[str, EdgeAttribution] = {}
        self.strategy_edges: dict[str, set[str]] = collections.defaultdict(set)

    @staticmethod
    def fingerprint_parser_state(payload: bytes, res: RunResult) -> set[str]:
        """Compute structural branch & state fingerprints reached by an input."""
        states = set()

        # Outcome state
        states.add(f"exit:{res.returncode}")
        states.add(f"outcome:{res.outcome.value}")

        # Diagnostic state branches
        for diag in res.diagnostics:
            states.add(f"diag_state:{diag}")

        # Lexical and token-level state transitions
        if b"<" in payload:
            states.add("token:lt")
        if b">" in payload:
            states.add("token:gt")
        if b"</" in payload:
            states.add("token:close_tag")
        if b"/>" in payload:
            states.add("token:self_close")
        if b"<!--" in payload:
            states.add("token:comment")
        if b"<![CDATA[" in payload:
            states.add("token:cdata")
        if b"<!DOCTYPE" in payload:
            states.add("token:doctype")
        if b"?" in payload and b"<?" in payload:
            states.add("token:pi")

        # Byte-level encoding states
        if payload.startswith(b"\xef\xbb\xbf"):
            states.add("bom:utf8")
        elif payload.startswith(b"\xff\xfe") or payload.startswith(b"\xfe\xff"):
            states.add("bom:utf16")

        # Nesting depth band
        depth = payload.count(b"<") - payload.count(b"</")
        band = min(max(0, depth), 20)
        states.add(f"depth_band:{band}")

        # Length scale band
        length_band = len(payload) // 256
        states.add(f"len_band:{min(length_band, 16)}")

        return states

    def analyze_strategy_corpus(
        self,
        strategy_name: str,
        payloads: Iterable[bytes],
    ) -> list[set[str]]:
        """Analyze a sequence of payloads belonging to a named strategy."""
        results = []
        for idx, payload in enumerate(payloads):
            res = self.target.run(payload)
            sha = hashlib.sha256(payload).hexdigest()
            states = self.fingerprint_parser_state(payload, res)
            results.append(states)

            for state in states:
                self.strategy_edges[strategy_name].add(state)
                if state not in self.edge_table:
                    self.edge_table[state] = EdgeAttribution(
                        edge_id=state,
                        discovered_by_strategy=strategy_name,
                        discovered_at_index=idx,
                        hit_count=1,
                        sample_sha=sha,
                    )
                else:
                    self.edge_table[state].hit_count += 1
        return results

    def compile_report(self) -> CoverageShadowReport:
        """Compile comprehensive shadow report showing total and unique edges per strategy."""
        total_edges = len(self.edge_table)
        edges_by_strat = {s: len(edges) for s, edges in self.strategy_edges.items()}

        # Calculate exclusive edges per strategy
        exclusive: dict[str, int] = collections.defaultdict(int)
        for state, attr in self.edge_table.items():
            # Count how many strategies reached this state
            reachers = [s for s, edges in self.strategy_edges.items() if state in edges]
            if len(reachers) == 1:
                exclusive[reachers[0]] += 1

        total_inputs = sum(attr.hit_count for attr in self.edge_table.values())

        return CoverageShadowReport(
            total_inputs_analyzed=total_inputs,
            total_edges_discovered=total_edges,
            edges_by_strategy=edges_by_strat,
            unique_edges_by_strategy=dict(exclusive),
            coverage_timeline=[],
            edge_details=list(self.edge_table.values()),
        )
